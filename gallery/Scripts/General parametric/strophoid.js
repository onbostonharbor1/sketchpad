function clearCanvas() {

  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.clearRect(0, 0, ctx.canvas.width, ctx.canvas.height);

} // end clearCanvas


function beginWorldTransform() {

  const w = ctx.canvas.width;
  const h = ctx.canvas.height;

  /* World coords:
     - origin at canvas center
     - +y is up (so we flip y) */
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.translate(w / 2, h / 2);
  ctx.scale(1, -1);

} // end beginWorldTransform


function drawAxes(p) {

  const w = ctx.canvas.width;
  const h = ctx.canvas.height;

  const xMin = -w / 2;
  const xMax =  w / 2;
  const yMin = -h / 2;
  const yMax =  h / 2;

  ctx.save();

  ctx.lineWidth = p.axisWidth;
  ctx.strokeStyle = p.axisColor;

  ctx.beginPath();

  /* x-axis */
  ctx.moveTo(xMin, 0);
  ctx.lineTo(xMax, 0);

  /* y-axis */
  ctx.moveTo(0, yMin);
  ctx.lineTo(0, yMax);

  ctx.stroke();

  ctx.restore();

} // end drawAxes


function drawNode(p) {

  ctx.save();

  ctx.fillStyle = p.nodeColor;

  ctx.beginPath();
  ctx.arc(0, 0, p.nodeRadius, 0, Math.PI * 2);
  ctx.fill();

  ctx.restore();

} // end drawNode


function drawOutline(points, p) {

  ctx.save();

  ctx.lineWidth = p.outlineWidth;
  ctx.strokeStyle = p.outlineColor;

  ctx.beginPath();
  ctx.moveTo(points[0].x, points[0].y);

  for (let i = 1; i < points.length; i++) {
    ctx.lineTo(points[i].x, points[i].y);
  }

  ctx.stroke();

  ctx.restore();

} // end drawOutline


/* ============================================================
   Curve-stitch rendering

   We build two sequences:
     A[i] = points[i]
     B[i] = points[rev(i)] where rev(i) = (N-1-i) + offset  (wrapped)

   Then draw stitch lines from A[i] to B[i], skipping by stitchEvery.

============================================================ */
function drawStitches(points, p) {

  const n = points.length;

  ctx.save();

  ctx.lineWidth = p.stitchWidth;
  ctx.strokeStyle = p.stitchColor;

  ctx.beginPath();

  for (let i = 0; i < n; i += p.stitchEvery) {

    let j = (n - 1 - i) + p.stitchOffset;

    /* Wrap j into [0, n-1]. */
    j = j % n;
    if (j < 0) j += n;

    ctx.moveTo(points[i].x, points[i].y);
    ctx.lineTo(points[j].x, points[j].y);

  }

  ctx.stroke();
  ctx.restore();

} // end drawStitches


/* ============================================================
   Update / Draw lifecycle (drawRegistry-style)
============================================================ */
function init(p) {

  scriptInfo.elements = {
    element: {
      points: []
    }
  };

} // end init


function update(p) {

  scriptInfo.elements.element.points = generatePoints(p);

} // end update


function draw(p) {

  clearCanvas();

  beginWorldTransform();

  if (p.showAxes) {
    drawAxes(p);
  }

  drawStitches(scriptInfo.elements.element.points, p);

  if (p.showOutline) {
    drawOutline(scriptInfo.elements.element.points, p);
  }

  if (p.showNode) {
    drawNode(p);
  }

} // end draw


