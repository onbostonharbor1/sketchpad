/* ============================================================
   Math helpers
============================================================ */
function toRadians(deg) {
  return (deg * Math.PI) / 180;
} // end toRadians


/* ============================================================
   Strophoid parametric: t -> {x,y}
   Uses the explicit form from the embedded text:

     x = a * tan(t)
     y = a * tan(t) * sin(t)

============================================================ */
function strophoidPointAt(t, p) {

  const tanT = Math.tan(t);

  return {
    x: p.a * tanT,
    y: p.a * tanT * Math.sin(t)
  };

} // end strophoidPointAt


/* ============================================================
   Sampling
============================================================ */
function generatePoints(p) {

  const pts = [];

  const steps = p.steps;

  const tMin = toRadians(p.tMinDeg);
  const tMax = toRadians(p.tMaxDeg);

  for (let i = 0; i < steps; i++) {

    const t = tMin + ((tMax - tMin) * i) / (steps - 1);
    const pt = strophoidPointAt(t, p);

    pts.push({ x: pt.x, y: pt.y, t: t });

  }

  return pts;

} // end generatePoints


